/** 递归将对象所有叶子值替换为 string */
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends object ? DeepStringify<T[K]> : string;
};

/** 语言包结构类型（所有值为 string） */
export type Locale = DeepStringify<typeof zh>;
